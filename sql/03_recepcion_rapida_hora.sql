-- Tabla DCI_HORA — Recepción Rápida (direct checkin) por hora
-- Nodo n8n: PEAK_DCI_HORA

-- ================================================================
-- DCI_HORA — versión con auto-ajuste de horario (DST-safe)
-- Mismo criterio que CHECKIN_HORA_AUTOADJUST.sql: reemplaza el
-- parche fijo "+1 HORA" por FN_API_TIMEZONE en todas las CTEs que
-- leen STOCK_MOVEMENTS / OPERATOR_EVENTS.
-- ================================================================
CREATE OR REPLACE TABLE `your-project.analytics.DCI_HORA` AS

WITH

first_day_dci AS (
  SELECT
    CAST(EMPLOYEE_ID AS STRING) AS OPERATOR_ID,
    MIN(FIRST_OPS_DAY) AS FIRST_DAY
  FROM `your-project.source.ATTENDANCE`
  WHERE FACILITY_ID = 'CD-01'
    AND SITE_ID = 'MLC'
    AND FIRST_OPS_DAY IS NOT NULL
  GROUP BY 1
),

ATT_PT AS (
  SELECT
    DATE(WORK_START_DATE) AS FECHA,
    CAST(USER_ID AS STRING) AS OPERATOR_ID,
    MAX(
      CASE
        WHEN REGEXP_CONTAINS(UPPER(COALESCE(SCHEDULE_NAME, '')), r'PTO') THEN 0
        WHEN REGEXP_CONTAINS(UPPER(COALESCE(SCHEDULE_NAME, '')), r'(^PT)|(\bPT\b)|(PT$)|(XDPT)|(PT[0-9])')
          OR REGEXP_CONTAINS(UPPER(COALESCE(SCHEDULE_DESCRIPTION, '')), r'(^PT)|(\bPT\b)|(PT$)|(XDPT)|(PT[0-9])')
        THEN 1
        ELSE 0
      END
    ) AS IS_PT
  FROM `your-project.source.ATTENDANCE`
  WHERE SITE_ID = 'MLC'
    AND FACILITY_ID = 'CD-01'
    AND DATE(WORK_START_DATE) >= DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY)
    AND DATE(WORK_START_DATE) <= CURRENT_DATE('America/Santiago')
    AND USER_ID IS NOT NULL
  GROUP BY FECHA, OPERATOR_ID
),

PROCESO_PRINCIPAL AS (
  SELECT
    OPERATOR_ID,
    PROCESS AS PROCESO_PRINCIPAL
  FROM (
    SELECT
      CAST(OPERATOR_ID AS STRING) AS OPERATOR_ID,
      PROCESS,
      SUM(COALESCE(PROCESS_DURATION, 0)) AS HH_PROCESO
    FROM `your-project.source.EMPLOYEE_ATTRIBUTES`
    WHERE LOGISTIC_CENTER_ID = 'CD-01'
      AND START_DATE >= DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY)
      AND OPERATOR_ID IS NOT NULL
    GROUP BY OPERATOR_ID, PROCESS
  )
  QUALIFY ROW_NUMBER() OVER (PARTITION BY OPERATOR_ID ORDER BY HH_PROCESO DESC) = 1
),

CUBING AS (
  SELECT
    INVENTORY_ID,
    COALESCE(
      ITE_VOLUMEN,
      CASE
        WHEN ITE_HEIGHT > 0 AND ITE_LENGTH > 0 AND ITE_WIDTH > 0
        THEN ITE_HEIGHT * ITE_LENGTH * ITE_WIDTH / 1000.0
        ELSE NULL
      END
    ) AS VOL_LITROS,
    CASE
      WHEN FLAG_TOTABLE = TRUE OR TOTABILITY = 'TOTABLE' THEN TRUE
      ELSE FALSE
    END AS FLAG_TOTABLE,
    CASE
      WHEN UPPER(COALESCE(ITE_WEIGHT_UNIT, '')) IN ('G', 'GR', 'GRAM', 'GRAMS')
      THEN SAFE_DIVIDE(ITE_WEIGHT, 1000.0)
      ELSE ITE_WEIGHT
    END AS PESO_KG,
    CASE
      WHEN ITE_VOLUMEN IS NOT NULL AND ITE_VOLUMEN > 0 THEN 'ITE_VOLUMEN'
      WHEN ITE_HEIGHT > 0 AND ITE_LENGTH > 0 AND ITE_WIDTH > 0 THEN 'CALCULADO'
      ELSE 'SIN_VOLUMETRIA'
    END AS FUENTE_VOLUMEN
  FROM `your-project.source.SKU_DETAILS`
  WHERE LOGISTIC_CENTER_ID = 'CD-01'
    AND SIT_SITE_ID = 'MLC'
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY INVENTORY_ID
    ORDER BY (ITE_VOLUMEN IS NOT NULL) DESC, (ITE_HEIGHT IS NOT NULL) DESC
  ) = 1
),

OPS_DCI AS (
  SELECT DISTINCT
    CAST(OPERATOR_ID AS STRING) AS OPERATOR_ID,
    DATE(START_DATE) AS FECHA
  FROM `your-project.source.OPERATOR_PRODUCTIVITY`
  WHERE AREA = 'inbound'
    AND PROCESS = 'direct_checkin'
    AND DATE(START_DATE) >= DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY)
    AND LOGISTIC_CENTER_ID = 'CD-01'
    AND SITE_ID = 'MLC'
),

-- ================================================================
-- TOTE FLAG — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
TOT_FLAG AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS HORA,
    ROUND(
      SAFE_DIVIDE(
        SUM(CASE WHEN c.FLAG_TOTABLE IS TRUE THEN m.FBM_QUANTITY ELSE 0 END),
        NULLIF(SUM(m.FBM_QUANTITY), 0)
      ), 6
    ) AS PCT_TOTEABLE
  FROM `your-project.source.STOCK_MOVEMENTS` m
  INNER JOIN OPS_DCI ops
    ON ops.OPERATOR_ID = CAST(m.FBM_USER_ID AS STRING)
   AND ops.FECHA = DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM))
  LEFT JOIN CUBING c ON m.INVENTORY_ID = c.INVENTORY_ID
  WHERE m.WAREHOUSE_ID = 'CD-01'
    AND m.FBM_REASON_PROCESS = 'inbound'
    AND m.ADDRESS_FROM IS NULL
    AND m.ADDRESS_TO LIKE 'MU-%'
    AND m.AUD_INS_DTTM >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND m.AUD_INS_DTTM <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA
),

-- ================================================================
-- TOTE LMS — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
TOTE_LMS AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', EVENT_DATE)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', EVENT_DATE)) AS HORA,
    ROUND(SAFE_DIVIDE(COUNTIF(UPPER(JSON_VALUE(ATTRIBUTES, '$.tote_size')) = 'XS'), NULLIF(COUNTIF(JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL), 0)), 6) AS PCT_XS,
    ROUND(SAFE_DIVIDE(COUNTIF(UPPER(JSON_VALUE(ATTRIBUTES, '$.tote_size')) = 'S'),  NULLIF(COUNTIF(JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL), 0)), 6) AS PCT_S,
    ROUND(SAFE_DIVIDE(COUNTIF(UPPER(JSON_VALUE(ATTRIBUTES, '$.tote_size')) = 'M'),  NULLIF(COUNTIF(JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL), 0)), 6) AS PCT_M,
    ROUND(SAFE_DIVIDE(COUNTIF(UPPER(JSON_VALUE(ATTRIBUTES, '$.tote_size')) = 'L'),  NULLIF(COUNTIF(JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL), 0)), 6) AS PCT_L,
    ROUND(SAFE_DIVIDE(COUNTIF(UPPER(JSON_VALUE(ATTRIBUTES, '$.tote_size')) = 'XL'), NULLIF(COUNTIF(JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL), 0)), 6) AS PCT_XL
  FROM `your-project.source.OPERATOR_EVENTS`
  WHERE FACILITY = 'CD-01'
    AND PROCESS = 'direct_checkin'
    AND JSON_VALUE(ATTRIBUTES, '$.tote_size') IS NOT NULL
    AND EVENT_DATE >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND EVENT_DATE <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA
),

-- ================================================================
-- VOLUMETRÍA Y PESO POR HORA — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
VOL_RATIO AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS HORA,
    ROUND(SAFE_DIVIDE(SUM(CASE WHEN c.FLAG_TOTABLE IS TRUE AND c.VOL_LITROS IS NOT NULL THEN m.FBM_QUANTITY * c.VOL_LITROS END), NULLIF(SUM(CASE WHEN c.FLAG_TOTABLE IS TRUE AND c.VOL_LITROS IS NOT NULL THEN m.FBM_QUANTITY END), 0)), 3) AS L_POR_UD_TOTEABLE,
    ROUND(SAFE_DIVIDE(SUM(CASE WHEN c.FLAG_TOTABLE IS NOT TRUE AND c.VOL_LITROS IS NOT NULL THEN m.FBM_QUANTITY * c.VOL_LITROS END), NULLIF(SUM(CASE WHEN c.FLAG_TOTABLE IS NOT TRUE AND c.VOL_LITROS IS NOT NULL THEN m.FBM_QUANTITY END), 0)), 3) AS L_POR_UD_NO_TOTEABLE,
    ROUND(SAFE_DIVIDE(SUM(CASE WHEN c.FLAG_TOTABLE IS TRUE THEN m.FBM_QUANTITY * COALESCE(c.PESO_KG, 0) END), NULLIF(SUM(CASE WHEN c.FLAG_TOTABLE IS TRUE THEN m.FBM_QUANTITY END), 0)), 3) AS KG_POR_UD_TOTEABLE,
    ROUND(SAFE_DIVIDE(SUM(CASE WHEN c.FLAG_TOTABLE IS NOT TRUE THEN m.FBM_QUANTITY * COALESCE(c.PESO_KG, 0) END), NULLIF(SUM(CASE WHEN c.FLAG_TOTABLE IS NOT TRUE THEN m.FBM_QUANTITY END), 0)), 3) AS KG_POR_UD_NO_TOTEABLE
  FROM `your-project.source.STOCK_MOVEMENTS` m
  LEFT JOIN CUBING c ON m.INVENTORY_ID = c.INVENTORY_ID
  WHERE m.WAREHOUSE_ID = 'CD-01'
    AND m.FBM_REASON_PROCESS = 'inbound'
    AND m.ADDRESS_FROM IS NULL
    AND m.ADDRESS_TO LIKE 'MU-%'
    AND m.AUD_INS_DTTM >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND m.AUD_INS_DTTM <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA
),

BASE_DCI AS (
  SELECT
    p.START_DATE AS FECHA,
    CAST(p.OPERATOR_ID AS STRING) AS OPERATOR_ID,
    p.LDAP_USER,
    SUM(p.UNITS) AS UNITS_PROCESSED
  FROM `your-project.source.OPERATOR_PRODUCTIVITY` p
  WHERE p.LOGISTIC_CENTER_ID = 'CD-01'
    AND p.AREA = 'inbound'
    AND p.PROCESS = 'direct_checkin'
    AND p.START_DATE >= DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY)
    AND p.START_DATE <= CURRENT_DATE('America/Santiago')
    AND p.LDAP_USER IS NOT NULL
    AND p.LDAP_USER NOT IN (SELECT LDAP_USER FROM `your-project.config.USUARIOS_EXCLUIDOS`)  -- supervisores, pruebas, etc.
  GROUP BY FECHA, OPERATOR_ID, LDAP_USER
),

-- ================================================================
-- ACTIVIDAD HORA — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
ACTIVIDAD_HORA AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS HORA,
    CAST(m.FBM_USER_ID AS STRING) AS OPERATOR_ID
  FROM `your-project.source.STOCK_MOVEMENTS` m
  INNER JOIN BASE_DCI bp
    ON bp.OPERATOR_ID = CAST(m.FBM_USER_ID AS STRING)
   AND bp.FECHA = DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM))
  WHERE m.WAREHOUSE_ID = 'CD-01'
    AND m.FBM_REASON_PROCESS = 'inbound'
    AND m.ADDRESS_FROM IS NULL
    AND m.ADDRESS_TO LIKE 'MU-%'
    AND m.AUD_INS_DTTM >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND m.AUD_INS_DTTM <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA, OPERATOR_ID
),

-- ================================================================
-- MOVIMIENTOS VOL — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
MOVIMIENTOS_VOL AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS HORA,
    CAST(m.FBM_USER_ID AS STRING) AS OPERATOR_ID,
    SUM(m.FBM_QUANTITY) AS UDS_MOV,
    SUM(m.FBM_QUANTITY * c.VOL_LITROS) AS VOL_TOTAL,
    SUM(m.FBM_QUANTITY * COALESCE(c.PESO_KG, 0)) AS PESO_TOTAL,
    SUM(CASE WHEN c.VOL_LITROS IS NOT NULL THEN m.FBM_QUANTITY ELSE 0 END) AS UDS_CON_VOL,
    SUM(CASE WHEN c.VOL_LITROS IS NULL THEN m.FBM_QUANTITY ELSE 0 END) AS UDS_SIN_VOL
  FROM `your-project.source.STOCK_MOVEMENTS` m
  LEFT JOIN CUBING c ON m.INVENTORY_ID = c.INVENTORY_ID
  WHERE m.WAREHOUSE_ID = 'CD-01'
    AND m.FBM_REASON_PROCESS = 'inbound'
    AND m.ADDRESS_FROM IS NULL
    AND m.ADDRESS_TO LIKE 'MU-%'
    AND m.AUD_INS_DTTM >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND m.AUD_INS_DTTM <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA, OPERATOR_ID
),

MOVIMIENTOS_VOL_DIA AS (
  SELECT
    FECHA, OPERATOR_ID,
    SUM(UDS_MOV) AS UDS_MOV_DIA,
    SUM(UDS_SIN_VOL) AS UDS_SIN_VOL_DIA
  FROM MOVIMIENTOS_VOL
  GROUP BY FECHA, OPERATOR_ID
),

BASE AS (
  SELECT
    ah.FECHA, ah.HORA, ah.OPERATOR_ID,
    bp.LDAP_USER, bp.UNITS_PROCESSED,
    COALESCE(mv.UDS_MOV, 0) AS UDS_MOV,
    COALESCE(mvd.UDS_MOV_DIA, 0) AS UDS_MOV_DIA,
    mv.VOL_TOTAL,
    COALESCE(mv.PESO_TOTAL, 0) AS PESO_TOTAL,
    COALESCE(mv.UDS_CON_VOL, 0) AS UDS_CON_VOL,
    COALESCE(mv.UDS_SIN_VOL, 0) AS UDS_SIN_VOL
  FROM ACTIVIDAD_HORA ah
  LEFT JOIN BASE_DCI bp ON bp.FECHA = ah.FECHA AND bp.OPERATOR_ID = ah.OPERATOR_ID
  LEFT JOIN MOVIMIENTOS_VOL mv ON mv.FECHA = ah.FECHA AND mv.HORA = ah.HORA AND mv.OPERATOR_ID = ah.OPERATOR_ID
  LEFT JOIN MOVIMIENTOS_VOL_DIA mvd ON mvd.FECHA = ah.FECHA AND mvd.OPERATOR_ID = ah.OPERATOR_ID
),

REPS_CLASIFICADOS AS (
  SELECT
    b.FECHA, b.HORA, b.OPERATOR_ID,
    CASE
      WHEN pp.PROCESO_PRINCIPAL != 'direct_checkin' THEN 'PALANCA EXT'
      WHEN att.IS_PT = 1 THEN 'PT'
      ELSE
        CASE
          WHEN fd.FIRST_DAY IS NULL THEN 'NH1'
          WHEN DATE_DIFF(DATE_TRUNC(b.FECHA, WEEK(SUNDAY)), DATE_TRUNC(fd.FIRST_DAY, WEEK(SUNDAY)), WEEK) = 0 THEN 'NH1'
          WHEN DATE_DIFF(DATE_TRUNC(b.FECHA, WEEK(SUNDAY)), DATE_TRUNC(fd.FIRST_DAY, WEEK(SUNDAY)), WEEK) = 1 THEN 'NH2'
          WHEN DATE_DIFF(DATE_TRUNC(b.FECHA, WEEK(SUNDAY)), DATE_TRUNC(fd.FIRST_DAY, WEEK(SUNDAY)), WEEK) = 2 THEN 'NH3'
          ELSE 'NATIVO'
        END
    END AS TIPO_REP
  FROM BASE b
  LEFT JOIN PROCESO_PRINCIPAL pp ON pp.OPERATOR_ID = b.OPERATOR_ID
  LEFT JOIN ATT_PT att ON att.OPERATOR_ID = b.OPERATOR_ID AND att.FECHA = b.FECHA
  LEFT JOIN first_day_dci fd ON fd.OPERATOR_ID = b.OPERATOR_ID
  QUALIFY ROW_NUMBER() OVER (PARTITION BY b.FECHA, b.HORA, b.OPERATOR_ID ORDER BY TIPO_REP) = 1
),

REP_SHARE AS (
  SELECT
    FECHA, HORA,
    COUNT(*) AS TOTAL_REPS,
    COUNTIF(TIPO_REP = 'NH1') AS N_NH1,
    COUNTIF(TIPO_REP = 'NH2') AS N_NH2,
    COUNTIF(TIPO_REP = 'NH3') AS N_NH3,
    COUNTIF(TIPO_REP = 'NATIVO') AS N_NATIVO,
    COUNTIF(TIPO_REP = 'PT') AS N_PT,
    COUNTIF(TIPO_REP = 'PALANCA EXT') AS N_PALANCA_EXT,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'NH1'), COUNT(*)) * 100, 1) AS PCT_NH1,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'NH2'), COUNT(*)) * 100, 1) AS PCT_NH2,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'NH3'), COUNT(*)) * 100, 1) AS PCT_NH3,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'NATIVO'), COUNT(*)) * 100, 1) AS PCT_NATIVO,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'PT'), COUNT(*)) * 100, 1) AS PCT_PT,
    ROUND(SAFE_DIVIDE(COUNTIF(TIPO_REP = 'PALANCA EXT'), COUNT(*)) * 100, 1) AS PCT_PALANCA_EXT
  FROM REPS_CLASIFICADOS
  GROUP BY FECHA, HORA
),

REP_DIA AS (
  SELECT
    FECHA,
    COUNT(DISTINCT OPERATOR_ID) AS TOTAL_REPS_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH1' THEN OPERATOR_ID END) AS N_NH1_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH2' THEN OPERATOR_ID END) AS N_NH2_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH3' THEN OPERATOR_ID END) AS N_NH3_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'NATIVO' THEN OPERATOR_ID END) AS N_NATIVO_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'PT' THEN OPERATOR_ID END) AS N_PT_DIA,
    COUNT(DISTINCT CASE WHEN TIPO_REP = 'PALANCA EXT' THEN OPERATOR_ID END) AS N_PALANCA_EXT_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH1' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_NH1_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH2' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_NH2_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'NH3' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_NH3_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'NATIVO' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_NATIVO_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'PT' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_PT_DIA,
    ROUND(SAFE_DIVIDE(COUNT(DISTINCT CASE WHEN TIPO_REP = 'PALANCA EXT' THEN OPERATOR_ID END), COUNT(DISTINCT OPERATOR_ID)) * 100, 1) AS PCT_PALANCA_EXT_DIA
  FROM REPS_CLASIFICADOS
  GROUP BY FECHA
),

VOLUMETRIA AS (
  SELECT
    FECHA, HORA,
    ROUND(SUM(SAFE_DIVIDE(CAST(UNITS_PROCESSED AS FLOAT64) * UDS_MOV, NULLIF(UDS_MOV_DIA, 0)))) AS UDS_DCI,
    ROUND(SUM(VOL_TOTAL), 2) AS VOL_L_TOTAL,
    ROUND(SAFE_DIVIDE(SUM(VOL_TOTAL), SUM(CASE WHEN VOL_TOTAL IS NOT NULL THEN UDS_MOV END)), 3) AS L_POR_UD,
    ROUND(SAFE_DIVIDE(SUM(PESO_TOTAL), SUM(UDS_MOV)), 3) AS KG_POR_UD,
    SUM(UDS_SIN_VOL) AS UDS_SIN_VOLUMEN,
    ROUND(SAFE_DIVIDE(SUM(UDS_CON_VOL), SUM(UDS_CON_VOL) + SUM(UDS_SIN_VOL)) * 100, 1) AS PCT_COBERTURA_VOL
  FROM BASE
  GROUP BY FECHA, HORA
),

-- ================================================================
-- PESO Y VOLUMEN POR TOTE — auto-ajuste vía FN_API_TIMEZONE
-- ================================================================
TOTE_PESO AS (
  SELECT
    DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS FECHA,
    EXTRACT(HOUR FROM `your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM)) AS HORA,
    m.ADDRESS_TO AS tote_address,
    SUM(CAST(m.FBM_QUANTITY AS FLOAT64) * COALESCE(c.PESO_KG, 0)) AS tote_weight_kg,
    SUM(CAST(m.FBM_QUANTITY AS FLOAT64) * c.VOL_LITROS) AS tote_vol_litros
  FROM `your-project.source.STOCK_MOVEMENTS` m
  INNER JOIN OPS_DCI ops
    ON ops.OPERATOR_ID = CAST(m.FBM_USER_ID AS STRING)
   AND ops.FECHA = DATE(`your-project.udf.FN_TIMEZONE`('MLC', m.AUD_INS_DTTM))
  INNER JOIN CUBING c ON m.INVENTORY_ID = c.INVENTORY_ID AND c.FLAG_TOTABLE IS TRUE
  WHERE m.WAREHOUSE_ID = 'CD-01'
    AND m.FBM_REASON_PROCESS = 'inbound'
    AND m.ADDRESS_FROM IS NULL
    AND m.ADDRESS_TO LIKE 'MU-%'
    AND m.AUD_INS_DTTM >= DATETIME(TIMESTAMP(DATE_SUB(CURRENT_DATE('America/Santiago'), INTERVAL 30 DAY), 'America/Santiago'))
    AND m.AUD_INS_DTTM <  DATETIME(TIMESTAMP(DATE_ADD(CURRENT_DATE('America/Santiago'), INTERVAL 1 DAY), 'America/Santiago'))
  GROUP BY FECHA, HORA, tote_address
),

TOTE_BINS AS (
  SELECT
    FECHA, HORA,
    COUNT(*) AS TOTAL_TOTES,
    ROUND(AVG(tote_weight_kg), 2) AS KG_POR_TOTE_AVG,
    ROUND(SUM(tote_weight_kg), 2) AS KG_TOTAL_TOTES,
    COUNTIF(tote_weight_kg > 0 AND tote_weight_kg <= 2) AS N_TOTES_0_2,
    COUNTIF(tote_weight_kg > 2 AND tote_weight_kg <= 4) AS N_TOTES_2_4,
    COUNTIF(tote_weight_kg > 4 AND tote_weight_kg <= 6) AS N_TOTES_4_6,
    COUNTIF(tote_weight_kg > 6 AND tote_weight_kg <= 8) AS N_TOTES_6_8,
    COUNTIF(tote_weight_kg > 8 AND tote_weight_kg <= 10) AS N_TOTES_8_10,
    COUNTIF(tote_weight_kg > 10 AND tote_weight_kg <= 12) AS N_TOTES_10_12,
    COUNTIF(tote_weight_kg > 12 AND tote_weight_kg <= 16) AS N_TOTES_12_16,
    COUNTIF(tote_weight_kg > 16) AS N_TOTES_16_MAS,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 0 AND tote_weight_kg <= 2), COUNT(*)) * 100, 1) AS PCT_TOTES_0_2,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 2 AND tote_weight_kg <= 4), COUNT(*)) * 100, 1) AS PCT_TOTES_2_4,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 4 AND tote_weight_kg <= 6), COUNT(*)) * 100, 1) AS PCT_TOTES_4_6,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 6 AND tote_weight_kg <= 8), COUNT(*)) * 100, 1) AS PCT_TOTES_6_8,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 8 AND tote_weight_kg <= 10), COUNT(*)) * 100, 1) AS PCT_TOTES_8_10,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 10 AND tote_weight_kg <= 12), COUNT(*)) * 100, 1) AS PCT_TOTES_10_12,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 12 AND tote_weight_kg <= 16), COUNT(*)) * 100, 1) AS PCT_TOTES_12_16,
    ROUND(SAFE_DIVIDE(COUNTIF(tote_weight_kg > 16), COUNT(*)) * 100, 1) AS PCT_TOTES_16_MAS,
    ROUND(AVG(LEAST(SAFE_DIVIDE(COALESCE(tote_vol_litros, 0), 51.408) * 100, 100.0)), 1) AS PCT_VOL_FULL_AVG,
    ROUND(AVG(LEAST(SAFE_DIVIDE(tote_weight_kg, 15.0) * 100, 100.0)), 1) AS PCT_PESO_FULL_AVG,
    ROUND(AVG(LEAST(GREATEST(SAFE_DIVIDE(COALESCE(tote_vol_litros, 0), 51.408), SAFE_DIVIDE(tote_weight_kg, 15.0)) * 100, 100.0)), 1) AS PCT_SATURA_FULL_AVG
  FROM TOTE_PESO
  GROUP BY FECHA, HORA
),

DCI_BASE AS (
  SELECT
    rs.FECHA, rs.HORA,
    rs.TOTAL_REPS, rs.N_NH1, rs.N_NH2, rs.N_NH3, rs.N_NATIVO, rs.N_PT, rs.N_PALANCA_EXT,
    rs.PCT_NH1, rs.PCT_NH2, rs.PCT_NH3, rs.PCT_NATIVO, rs.PCT_PT, rs.PCT_PALANCA_EXT,
    rd.TOTAL_REPS_DIA, rd.N_NH1_DIA, rd.N_NH2_DIA, rd.N_NH3_DIA, rd.N_NATIVO_DIA, rd.N_PT_DIA, rd.N_PALANCA_EXT_DIA,
    rd.PCT_NH1_DIA, rd.PCT_NH2_DIA, rd.PCT_NH3_DIA, rd.PCT_NATIVO_DIA, rd.PCT_PT_DIA, rd.PCT_PALANCA_EXT_DIA,
    COALESCE(v.UDS_DCI, 0) AS UDS_DCI,
    v.VOL_L_TOTAL, v.L_POR_UD, v.KG_POR_UD,
    COALESCE(v.UDS_SIN_VOLUMEN, 0) AS UDS_SIN_VOLUMEN,
    COALESCE(v.PCT_COBERTURA_VOL, 0) AS PCT_COBERTURA_VOL,
    vr.L_POR_UD_TOTEABLE, vr.L_POR_UD_NO_TOTEABLE, vr.KG_POR_UD_TOTEABLE, vr.KG_POR_UD_NO_TOTEABLE,
    CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) AS UDS_TOTEABLE,
    COALESCE(v.UDS_DCI, 0) - CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) AS UDS_NO_TOTEABLE,
    CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_XS, 0)) AS INT64) AS UDS_XS,
    CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_S, 0)) AS INT64) AS UDS_S,
    CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_M, 0)) AS INT64) AS UDS_M,
    CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_L, 0)) AS INT64) AS UDS_L,
    CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64)
      - CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_XS, 0)) AS INT64)
      - CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_S, 0)) AS INT64)
      - CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_M, 0)) AS INT64)
      - CAST(ROUND(CAST(ROUND(COALESCE(v.UDS_DCI, 0) * COALESCE(tf.PCT_TOTEABLE, 0)) AS INT64) * COALESCE(tl.PCT_L, 0)) AS INT64) AS UDS_XL,
    COALESCE(tb.TOTAL_TOTES, 0) AS TOTAL_TOTES,
    tb.KG_POR_TOTE_AVG, tb.KG_TOTAL_TOTES,
    COALESCE(tb.N_TOTES_0_2, 0) AS N_TOTES_0_2,
    COALESCE(tb.N_TOTES_2_4, 0) AS N_TOTES_2_4,
    COALESCE(tb.N_TOTES_4_6, 0) AS N_TOTES_4_6,
    COALESCE(tb.N_TOTES_6_8, 0) AS N_TOTES_6_8,
    COALESCE(tb.N_TOTES_8_10, 0) AS N_TOTES_8_10,
    COALESCE(tb.N_TOTES_10_12, 0) AS N_TOTES_10_12,
    COALESCE(tb.N_TOTES_12_16, 0) AS N_TOTES_12_16,
    COALESCE(tb.N_TOTES_16_MAS, 0) AS N_TOTES_16_MAS,
    tb.PCT_TOTES_0_2, tb.PCT_TOTES_2_4, tb.PCT_TOTES_4_6, tb.PCT_TOTES_6_8,
    tb.PCT_TOTES_8_10, tb.PCT_TOTES_10_12, tb.PCT_TOTES_12_16, tb.PCT_TOTES_16_MAS,
    tb.PCT_VOL_FULL_AVG, tb.PCT_PESO_FULL_AVG, tb.PCT_SATURA_FULL_AVG
  FROM REP_SHARE rs
  LEFT JOIN REP_DIA rd ON rd.FECHA = rs.FECHA
  LEFT JOIN VOLUMETRIA v ON v.FECHA = rs.FECHA AND v.HORA = rs.HORA
  LEFT JOIN VOL_RATIO vr ON vr.FECHA = rs.FECHA AND vr.HORA = rs.HORA
  LEFT JOIN TOT_FLAG tf ON tf.FECHA = rs.FECHA AND tf.HORA = rs.HORA
  LEFT JOIN TOTE_LMS tl ON tl.FECHA = rs.FECHA AND tl.HORA = rs.HORA
  LEFT JOIN TOTE_BINS tb ON tb.FECHA = rs.FECHA AND tb.HORA = rs.HORA
)

SELECT
  *,
  ROUND(SAFE_DIVIDE(UDS_TOTEABLE, NULLIF(UDS_DCI, 0)) * 100, 1) AS PCT_TOTEABLE,
  ROUND(SAFE_DIVIDE(UDS_XS, NULLIF(UDS_TOTEABLE, 0)) * 100, 1) AS PCT_TOTE_XS,
  ROUND(SAFE_DIVIDE(UDS_S,  NULLIF(UDS_TOTEABLE, 0)) * 100, 1) AS PCT_TOTE_S,
  ROUND(SAFE_DIVIDE(UDS_M,  NULLIF(UDS_TOTEABLE, 0)) * 100, 1) AS PCT_TOTE_M,
  ROUND(SAFE_DIVIDE(UDS_L,  NULLIF(UDS_TOTEABLE, 0)) * 100, 1) AS PCT_TOTE_L,
  ROUND(SAFE_DIVIDE(UDS_XL, NULLIF(UDS_TOTEABLE, 0)) * 100, 1) AS PCT_TOTE_XL
FROM DCI_BASE
ORDER BY FECHA, HORA;
